"""
Word accuracy with the static-letter model (option A, decided 22 Nov 2026).

The letter model is trained on the 30 static letters only; the lexicon keeps all
54 words, and a dynamic letter in a word is a decoder slot (word_decode.py,
web/word_decode.js). Compared with the 40-letter model on the same 218 dataset
clips, holds found unaided by Algorithm 2, test signer held out:

  1. offline: Platt probabilities + likelihood ratio, (ins, dele) tuned on the
     four training signers (as model_alternatives.ipynb section 4, SVM, seed 0)
  2. browser: vote share, ins 0, dele -0.5, no prior -- the page's settings --
     decoded by the actual web/word_decode.js (decode_clips.mjs), including
     how often a word is shown and how often a shown word is right.

Run from the repo root: python results/2026-11-22_static_words/run.py
"""
import json, os, subprocess, sys
import numpy as np, pandas as pd

sys.path.insert(0, ".")
import end_to_end as e2e, word_decode as wd, evaluation as ev
from splits import DYNAMIC_LETTERS

OUT = os.path.dirname(os.path.abspath(__file__))
DYN = set(DYNAMIC_LETTERS)


def has_dyn(word, lex):
    return any(l in DYN for l in lex[word])


def summarise(t, name):
    sg = t.signer.to_numpy()
    r1 = ev.summarise("", t.top1.to_numpy(), sg); r3 = ev.summarise("", t.top3.to_numpy(), sg)
    return {"setting": name, "clips": len(t),
            "top-1 %": r1["mean of folds %"], "CI lo": r1["boot lo %"], "CI hi": r1["boot hi %"],
            "top-3 %": r3["mean of folds %"]}


# ---- 1. offline decoder ------------------------------------------------------
rows, per = [], {}
for static in (False, True):
    nested, lex = e2e.nested_clips(scores="proba", seed=0, static_only=static)
    wl = DYNAMIC_LETTERS if static else ()
    parts = []
    for s, d in nested.items():
        ins, dele = wd.tune_aligned(d["tune"], lex, "free", True, wild_letters=wl)
        dec = lambda probs, classes, lx, clip, a=ins, b=dele: wd.decode_aligned(
            probs, classes, lx, clip["prior"], a, b, wild_letters=wl)
        t = e2e.word_table(d["test"], lex, dec, "free"); t["ins"], t["dele"] = ins, dele
        parts.append(t)
    t = pd.concat(parts, ignore_index=True)
    t["dynamic_word"] = [has_dyn(w, lex) for w in t.word]
    name = "30 static letters + slots" if static else "40 letters (before)"
    per[name] = t
    rows.append(summarise(t, f"offline, {name}"))
    for flag, lab in ((True, "words with a moving letter"), (False, "fully static words")):
        rows.append(summarise(t[t.dynamic_word == flag], f"   {lab}"))
    print(name, "tuned (ins, dele) per fold:", t.groupby("signer")[["ins", "dele"]].first().to_dict("index"))

off = pd.DataFrame(rows).round(1)
print(off.to_string(index=False))
pd.concat([t.assign(model=n) for n, t in per.items()]).to_csv(os.path.join(OUT, "offline_per_clip.csv"), index=False)
print("paired, 30 vs 40, offline top-1:",
      ev.summarise("", per["30 static letters + slots"].top1.to_numpy(),
                   per["30 static letters + slots"].signer.to_numpy(),
                   baseline=per["40 letters (before)"].top1.to_numpy()))

# ---- 2. browser decoder (actual JS) ------------------------------------------
dump = {}
for static in (False, True):
    clips, lex = e2e.loso_clips(scores="vote", static_only=static)
    dump["static" if static else "all"] = [
        {"signer": c["signer"], "word": c["word"], "classes": c["classes"],
         "probs": np.asarray(c["free"]).tolist()} for c in clips]
dump["lexicon"] = lex
dump["dynamic_letters"] = list(DYNAMIC_LETTERS)
path = os.path.join(OUT, "vote_clips.json")
json.dump(dump, open(path, "w", encoding="utf-8"), ensure_ascii=False)
res = subprocess.run(["node", os.path.join(OUT, "decode_clips.mjs"), path],
                     capture_output=True, text=True, check=True)
B = pd.DataFrame(json.loads(res.stdout))
os.remove(path)                      # 5 MB of derived scores; regenerated by this script
B["dynamic_word"] = [has_dyn(w, lex) for w in B.word]
B.to_csv(os.path.join(OUT, "browser_per_clip.csv"), index=False)

rows = []
for model in ("all", "static"):
    t = B[B.model == model]
    name = "40 letters (before)" if model == "all" else "30 static letters + slots"
    for sub, lab in ((t, name), (t[t.dynamic_word], "   words with a moving letter"),
                     (t[~t.dynamic_word], "   fully static words")):
        r = summarise(sub, f"browser, {lab}")
        for rule in ("shown", "shown_agree2", "shown_agree3"):
            sh = sub[rule].astype(bool)
            r[f"{rule} %"] = 100 * sh.mean()
            r[f"{rule} right %"] = 100 * sub.top1[sh].mean() if sh.any() else np.nan
        rows.append(r)
br = pd.DataFrame(rows).round(1)
print(br.to_string(index=False))
off.to_csv(os.path.join(OUT, "offline_summary.csv"), index=False)
br.to_csv(os.path.join(OUT, "browser_summary.csv"), index=False)
